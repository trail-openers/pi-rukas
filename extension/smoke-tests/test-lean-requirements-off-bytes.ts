#!/usr/bin/env bun
/**
 * lean — the requirement lever's OFF state is byte-identical, and its ON state
 * is not.
 *
 * The lever exists to be measured: a bench campaign runs lean with and without it
 * on the SAME commit, so "off" has to mean the release without the lever, down to
 * the bytes a child reads. Assertion-style prompt tests cannot pin that — a check
 * for `prompt.includes(X)` still passes after the sentence around X is rewritten.
 * So this compares against GOLDEN BYTES captured in a checked-in fixture
 * (`lib/lean-requirements-golden.json`).
 *
 *   (a) with the switch unset, `specifyPrompt`, `challengePrompt` and `buildPrompt`
 *       for a fixed spec equal the fixture exactly;
 *   (b) the off-state text never mentions the requirement tool or the section, so
 *       a child of the control run is not told about a submission nobody judges;
 *   (c) with the lever on, `specifyPrompt` and `buildPrompt` DIFFER from the
 *       fixture — an inert switch is not a lever — and each differs from the
 *       off-state bytes only by an ADDED tail, so the control's text is still
 *       there underneath; `challengePrompt` does not differ, because the challenge
 *       step is out of scope for this lever.
 *
 * The fixture is regenerated by hand when a prompt is deliberately rewritten:
 * `bun run smoke-tests/lib/lean-requirements-fixture.ts --write`. A golden that no
 * longer matches is the point — it is the diff that says a change reached the
 * children of a run that was supposed to be the control.
 */

import { buildPrompt } from "../src/lean/build-prompt.ts";
import { challengePrompt } from "../src/lean/challenge-prompt.ts";
import { specifyPrompt } from "../src/lean/specify-prompt.ts";
import {
  GOLDEN_FROZEN,
  GOLDEN_RUNNER,
  GOLDEN_SPEC,
  GOLDEN_WT,
  buildRequirementsRecord,
  offPrompts,
  readGolden,
} from "./lib/lean-requirements-fixture.ts";

/** Where two prompts stop agreeing, as the surrounding text — for a failing message. */
function diffAt(control: string, lever: string): string {
  let i = 0;
  while (i < control.length && control[i] === lever[i]) i++;
  return `${i}: ${JSON.stringify(control.slice(Math.max(0, i - 12), i + 12))}`;
}

let exit = 0;
function assert(cond: boolean, msg: string): void {
  if (cond) console.log(`✓ ${msg}`);
  else {
    console.error(`✗ ${msg}`);
    exit = 1;
  }
}

/** The three prompts with the lever on, built from the same inputs as the fixture. */
function onPrompts(): Record<string, string> {
  return {
    specify: specifyPrompt({
      issue: 2161,
      spec: GOLDEN_SPEC,
      testRunner: GOLDEN_RUNNER,
      worktree: GOLDEN_WT,
      requirements: true,
    }),
    challenge: challengePrompt({
      issue: 2161,
      spec: GOLDEN_SPEC,
      frozenPaths: GOLDEN_FROZEN,
      worktree: GOLDEN_WT,
      testRunner: GOLDEN_RUNNER,
    }),
    build: buildPrompt({
      issue: 2161,
      spec: GOLDEN_SPEC,
      frozenPaths: GOLDEN_FROZEN,
      worktree: GOLDEN_WT,
      attempt: 1,
      testRunner: GOLDEN_RUNNER,
      requirements: buildRequirementsRecord(),
    }),
  };
}

const off = offPrompts();
const golden = readGolden();

// ---------------------------------------------------- (a) off is byte-identical
for (const name of ["specify", "challenge", "build"] as const) {
  assert(
    golden[name] === off[name],
    `(off) the ${name} prompt equals the checked-in golden bytes exactly`,
  );
}
assert(
  Object.keys(golden).sort().join(",") === "build,challenge,specify",
  `(off) the golden fixture holds the three prompts and nothing else (${Object.keys(golden).sort().join(",")})`,
);

// --------------------------------------------------------- (b) off says nothing
for (const [name, prompt] of Object.entries(off)) {
  assert(
    !prompt.includes("submit_requirements"),
    `(off) the ${name} prompt never names the requirement tool the step will not judge`,
  );
  assert(
    !prompt.includes("The requirements this run must satisfy") &&
      !prompt.includes("The requirement list"),
    `(off) the ${name} prompt carries neither the builder's requirement section nor the adversary's list section`,
  );
}

// -------------------------------------------------------------- (c) on differs
{
  const on = onPrompts();
  // The section is APPENDED to the control's text, never woven into it: the
  // off-state bytes stay a byte-for-byte prefix of the on-state bytes, so the
  // control run and the lever run differ by exactly what the lever adds and
  // nothing else. A rewrite of any control sentence — even one the lever did not
  // touch — fails this, which is what an `includes` test cannot catch.
  assert(
    on.specify !== golden.specify && on.specify.startsWith(golden.specify),
    `(on) the specify prompt differs from the golden bytes only by an appended block (diff at ${diffAt(golden.specify, on.specify)})`,
  );
  assert(
    on.specify.includes("submit_requirements") && on.specify.includes("## The requirement list"),
    "(on) the specify prompt asks for the numbered list and the call that carries it",
  );
  assert(
    on.build !== golden.build && on.build.startsWith(golden.build),
    `(on) the build prompt differs from the golden bytes only by an appended block (diff at ${diffAt(golden.build, on.build)})`,
  );
  assert(
    on.build.includes("## The requirements this run must satisfy") &&
      on.build.includes("**R1** [behaviour]") &&
      on.build.includes("**R3** [preserved]"),
    "(on) the build prompt carries the list with its ids, kinds and the uncovered preserved item",
  );
  // The challenge step is explicitly out of scope: the lever's whole claim is
  // that the extra judgement lands in `specify`, where the all-criteria rule
  // already lives. A challenge prompt that changed would say otherwise.
  assert(
    on.challenge === golden.challenge,
    "(on) the challenge prompt is UNCHANGED — the lever does not reach the challenge step",
  );
}

if (exit !== 0) {
  console.error(
    "\nIf a prompt was deliberately rewritten, regenerate the golden fixture:\n  bun run smoke-tests/lib/lean-requirements-fixture.ts --write",
  );
}
process.exit(exit);
