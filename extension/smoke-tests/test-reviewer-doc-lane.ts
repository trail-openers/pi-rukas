#!/usr/bin/env bun
/**
 * #1992 — the code-review role prompt no longer prescribes whole-project scans
 * or a review that runs half an hour over a diff.
 *
 * The per-dispatch builders (`lensPromptFor`, `buildAdversarialPrompt`) carry the
 * reviewer-lane brief; the role prompt is the other half of what the child reads,
 * and it contradicted them. `agents-base/code-review-specialist.md` prescribed a
 * "Step 2: Run Automated Checks" of SAST, dependency audit and type checking for
 * the same dispatched-with-a-diff reviewer, and a Risk Classification table whose
 * Review Time column started at "30+ min". A child told both obeys the doctrine
 * file that names the commands.
 *
 * Asserted against the SOURCE markdown, not `dist/`: `dist/prompts/standard/` is
 * gitignored and regenerated by `bun run build`, so the source is the thing a
 * contributor commits and the thing that can drift (same reason
 * `test-developer-doc-test-scope.ts` reads `agents-base/developer.md`).
 */

import { readFileSync } from "node:fs";
import path from "node:path";

let exit = 0;
function assert(cond: boolean, msg: string) {
  if (cond) console.log(`✓ ${msg}`);
  else {
    console.error(`✗ ${msg}`);
    exit = 1;
  }
}

const ROOT = path.resolve(import.meta.dirname, "..", "..");
const DOC = path.join(ROOT, "agents-base", "code-review-specialist.md");

// No existsSync guard: a missing or unreadable doc is the failure this test
// exists to catch, and `readFileSync` naming the path and the errno is a better
// report than an assertion that a file is empty.
const src = readFileSync(DOC, "utf8");
assert(src.length > 0, `non-vacuity: ${path.relative(ROOT, DOC)} is readable`);

// AC6 — the whole-project scans and the review-time column are gone, together
// with the headings that carried them (a prescription that comes back under a
// new heading is still the prescription). One assert per clause: a conjunctive
// assert reports one failure whichever clause regressed, so the message cannot
// name what came back.
for (const [needle, what] of [
  [/semgrep|eslint-security/i, "the SAST scan prescription"],
  [/dependency[ -]audit|npm audit|pip-audit/i, "the dependency-audit prescription"],
  [/Run Automated Checks/i, "the 'Run Automated Checks' step that prescribed them"],
  [/\b30\+ min\b/i, "the 30+ minute review-time row"],
  [/Review Time/i, "the Review Time column itself (a diff-scoped review has no time budget in doctrine)"],
] as const) {
  assert(!needle.test(src), `#1992 AC6: the role prompt no longer prescribes ${what}`);
}

// And the replacement really is there, so the section was re-scoped rather than
// deleted out from under the reviewer that still has to run a check.
assert(
  /targeted checks/i.test(src),
  "#1992 AC6: the role prompt asks for targeted checks on the changed paths",
);
assert(
  /whole-project/i.test(src) && /driver/i.test(src),
  "#1992 AC6: the role prompt says the whole-project gate belongs to the driver",
);
assert(
  /targeted checks[^\n]*passed/i.test(src),
  "#1992 AC6: approval evidence is the targeted checks, not 'all automated checks'",
);
assert(
  !/all automated checks/i.test(src),
  "#1992 AC6 canary: the 'All automated checks passed' approval gate is gone",
);

console.log(`\nexit ${exit}`);
process.exit(exit);
