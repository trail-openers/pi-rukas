#!/usr/bin/env bun
/**
 * #2160 — the four helper roles read the forge through `forge_read`, not `gh`/`glab`.
 *
 * A helper child carries no forge login (child-forge-env.ts deleted the five
 * token vars and redirected both config roots), so a role prompt that tells it
 * to "use your forge CLI for ALL operations" is sending a credential-less child
 * at an authenticated API: the read comes back unauthenticated (rate-limited,
 * refused on a private repo) or the child goes looking for a login it was
 * deliberately not given. The parent serves the same bytes through `forge_read`.
 *
 * Ops and the PM keep the login and their `gh`/`glab` text: they are the roles
 * that land work, and this file asserts their text is UNCHANGED so the rule
 * cannot be applied to them by accident.
 *
 * Asserted against the SOURCE markdown, not `dist/` — `dist/prompts/standard/`
 * is gitignored and regenerated by the build, so the source is what a
 * contributor commits and the thing that can drift (the same reason
 * `test-reviewer-doc-lane.ts` reads the source).
 */

import { readFileSync } from "node:fs";
import path from "node:path";

let exit = 0;
function assert(cond: boolean, msg: string) {
  if (cond) console.log(`✓ ${msg}`);
  else {
    console.error(`✗ ${msg}`);
    exit = 1;
  }
}

const ROOT = path.resolve(import.meta.dirname, "..", "..");
const read = (role: string): string =>
  // No existsSync guard: a missing role doc is the failure this test exists to
  // catch, and `readFileSync` naming the path and the errno reports it better.
  readFileSync(path.join(ROOT, "agents-base", `${role}.md`), "utf8");

/** A `gh`/`glab` READ verb — the thing a credential-less helper cannot run. */
const FORGE_READ_COMMAND =
  /\b(gh|glab)\s+(pr|issue|mr)\s+(view|diff|checks|list|comments|status|trace|reviews|approvals)\b/;

const HELPERS = ["code-review-specialist", "explore", "developer", "adversarial-developer"];

for (const role of HELPERS) {
  const src = read(role);
  assert(src.length > 0, `non-vacuity: agents-base/${role}.md is readable`);
  const hits = src.split("\n").filter((l) => FORGE_READ_COMMAND.test(l));
  assert(
    hits.length === 0,
    `${role}: no line tells the helper to read the forge with gh/glab (${hits
      .map((h) => h.trim().slice(0, 60))
      .join(" / ")})`,
  );
}

// The reviewer is the role that had the whole forge CLI section, so its doc must
// now name the tool that replaced it — otherwise the section was deleted rather
// than re-pointed, and the reviewer has no instruction at all.
assert(
  /forge_read/.test(read("code-review-specialist")),
  "code-review-specialist: the forge workflow names forge_read as the read path",
);
assert(
  !/Use your forge CLI for ALL operations/.test(read("code-review-specialist")),
  "code-review-specialist: the 'forge CLI for ALL operations' instruction is gone",
);
assert(
  /forge_read/.test(read("explore")),
  "explore: the role doc names forge_read as the forge read path",
);

// The negative arms: ops and the PM keep their login, so their `gh`/`glab` text
// is correct and must stay. A change that swept them in would fail here.
for (const role of ["ops", "project-manager"]) {
  const src = read(role);
  assert(
    /\b(gh|glab)\s+(pr|issue|mr)\s+(view|diff|checks|list|comment|merge|create)\b/.test(src),
    `${role}: still told to run the forge CLI directly (it keeps its login)`,
  );
}

console.log(`\nexit ${exit}`);
process.exit(exit);
