#!/usr/bin/env bun
/**
 * #2160 — the four helper roles read the forge through `forge_read`, not `gh`/`glab`.
 *
 * A helper child carries no forge login (child-forge-env.ts deleted the five
 * token vars and redirected both config roots), so a role prompt that tells it
 * to "use your forge CLI for ALL operations" is sending a credential-less child
 * at an authenticated API: the read comes back unauthenticated (rate-limited,
 * refused on a private repo) or the child goes looking for a login it was
 * deliberately not given. The parent serves the same bytes through `forge_read`.
 *
 * Ops and the PM keep the login and their `gh`/`glab` text: they are the roles
 * that land work, and this file asserts their text is UNCHANGED so the rule
 * cannot be applied to them by accident.
 *
 * The scan covers the WHOLE prompt a helper is assembled from, not just its
 * `agents-base/<role>.md`: a composed prompt is what the child reads, so a
 * `modules/` file pulled in by the role's own manifest is the same instruction
 * with one more step between it and the child. The manifest is the source that
 * says which modules a role gets, so the scan follows it rather than a list
 * maintained here that would drift the first time a manifest changes.
 *
 * Asserted against the SOURCE markdown, not `dist/` — `dist/prompts/standard/`
 * is gitignored and regenerated by the build, so the source is what a
 * contributor commits and the thing that can drift (the same reason
 * `test-reviewer-doc-lane.ts` reads the source).
 */

import { readFileSync } from "node:fs";
import path from "node:path";

let exit = 0;
function assert(cond: boolean, msg: string) {
  if (cond) console.log(`✓ ${msg}`);
  else {
    console.error(`✗ ${msg}`);
    exit = 1;
  }
}

const ROOT = path.resolve(import.meta.dirname, "..", "..");
const read = (role: string): string =>
  // No existsSync guard: a missing role doc is the failure this test exists to
  // catch, and `readFileSync` naming the path and the errno reports it better.
  readFileSync(path.join(ROOT, "agents-base", `${role}.md`), "utf8");

/**
 * The sources one helper's prompt is actually assembled from: the role doc plus
 * every module its manifest lists, in manifest order. Read from the manifest
 * rather than hardcoded, so the gate follows the composition instead of a copy
 * of it that goes stale.
 */
const promptSources = (role: string): { file: string; text: string }[] => {
  const manifest = readFileSync(path.join(ROOT, "manifests", `${role}.manifest`), "utf8")
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l.length > 0 && !l.startsWith("#"));
  assert(
    manifest.length > 0 && manifest[0] === `agents-base/${role}.md`,
    `${role}: its manifest names its own role doc first`,
  );
  return manifest.map((rel) => ({ file: rel, text: readFileSync(path.join(ROOT, rel), "utf8") }));
};

/**
 * The classifier, in one rule: a doctrine line that tells a reader to run a
 * `gh`/`glab` forge READ is a violation UNLESS the same line names `forge_read`
 * beside it. Role scope is carried by the prose, not by new machinery — a line
 * that reads "read issue content with `forge_read` (PM and ops: `gh issue view`)"
 * is true for every reader this module reaches, and the `forge_read` token is
 * what makes it true.
 *
 * Reads covered: the subcommand forms (`pr|issue|mr view|diff|checks|list|…`) and
 * the `gh api`/`glab api` REST fallback scoped to the forge's OWN resource paths.
 * That scope matters twice over: the same `gh api` subcommand reads a third-party
 * API (the JSON-parsing example in tool-preferences.md) and WRITES (`--method
 * POST`, `-X PUT`), and neither is a forge read this gate should claim. `comment`
 * is not in the read list — posting is a write, which a login-less helper cannot
 * do either, and the reviewer's MR-note arm legitimately documents it.
 *
 * A `glab api … mr merge` line is not a hit: `merge` is not in the read set, and
 * the merge doctrine belongs to ops, which holds a login.
 */
const FORGE_READ_SUBCOMMAND =
  /\b(gh|glab)\s+(pr|issue|mr)\s+(view|diff|checks|list|comments|status|trace|reviews|approvals)\b/;
const FORGE_API_READ =
  /\b(gh|glab)\s+api\b[^\n]*\/?(issues?|merge_requests|pulls?|actions|pipelines|jobs)\b/;
const FORGE_WRITE_METHOD = /--method\s+POST|-X\s+(PUT|POST|PATCH|DELETE)/;
const NAMES_FORGE_READ = /forge_read/;

/**
 * Lines carrying the exemption, resolved upward through a code fence's comment
 * header.
 *
 * A fence's body is the command and the prose above it is where the sentence
 * naming `forge_read` lives, so a check that only reads the command line asks the
 * shell comment to carry a sentence the fence's own comment already carries. The
 * walk stops at the fence opener: an exemption is scoped to one block, not to
 * everything above it, and a rule that exempts on sight of the token anywhere
 * earlier in the file is a rule that fires until someone deletes one sentence.
 */
const exemptionInScope = (lines: string[], i: number): boolean => {
  for (let j = i; j >= 0 && !/^\s*```/.test(lines[j] ?? ""); j--) {
    if (NAMES_FORGE_READ.test(lines[j] ?? "")) return true;
  }
  return false;
};

/** The lines of one doctrine source that send a credential-less helper at the API. */
const forgeReadHits = (text: string): string[] => {
  const lines = text.split("\n");
  return lines.filter(
    (l, i) =>
      !NAMES_FORGE_READ.test(l) &&
      !exemptionInScope(lines, i) &&
      (FORGE_READ_SUBCOMMAND.test(l) || (FORGE_API_READ.test(l) && !FORGE_WRITE_METHOD.test(l))),
  );
};

const HELPERS = ["code-review-specialist", "explore", "developer", "adversarial-developer"];

for (const role of HELPERS) {
  for (const src of promptSources(role)) {
    assert(src.text.length > 0, `non-vacuity: ${src.file} is readable (${role})`);
    const hits = forgeReadHits(src.text);
    assert(
      hits.length === 0,
      `${src.file} [${role}]: no line tells the helper to read the forge with gh/glab (${hits
        .map((h) => h.trim().slice(0, 60))
        .join(" / ")})`,
    );
  }
}

// The classifier is worth only what its arms prove. A line that names both sides
// — the tool and the CLI it stands for — must pass, and a bare forge REST read
// must not. Without these the gate is a keyword ban, and a keyword ban either
// over-flags the docs that fix the problem or is loosened until it flags nothing.
assert(
  forgeReadHits(
    "Read issue content with `forge_read` (PM and ops: `gh issue view <issue-number>`).",
  ).length === 0,
  "a line that names forge_read beside the CLI form is not a violation — the rule the modules now follow",
);
assert(
  forgeReadHits("Parse API responses: `gh api ... | jq '.items[]'` (GitHub)").length === 0,
  "a third-party `gh api` example with no forge path is not a forge read",
);
assert(
  forgeReadHits(
    'Post a note: `glab api -X POST -f "body=@f" /projects/:id/merge_requests/7/notes`',
  ).length === 0,
  "a documented forge WRITE is not a read violation",
);
assert(
  forgeReadHits("Fetch it with `gh api repos/o/r/issues/7`").length === 1,
  "non-vacuity: an unauthenticated forge REST read IS flagged",
);
assert(
  forgeReadHits("## Reading\n\nA helper reads with `forge_read`.\n\n```bash\ngh issue view 7\n```").length ===
    1,
  "the exemption does not leak past the fence it was written in",
);

// The reviewer is the role that had the whole forge CLI section, so its doc must
// now name the tool that replaced it — otherwise the section was deleted rather
// than re-pointed, and the reviewer has no instruction at all.
assert(
  /forge_read/.test(read("code-review-specialist")),
  "code-review-specialist: the forge workflow names forge_read as the read path",
);
assert(
  !/Use your forge CLI for ALL operations/.test(read("code-review-specialist")),
  "code-review-specialist: the 'forge CLI for ALL operations' instruction is gone",
);
assert(
  /forge_read/.test(read("explore")),
  "explore: the role doc names forge_read as the forge read path",
);

// The negative arms: ops and the PM keep their login, so their `gh`/`glab` text
// is correct and must stay. A change that swept them in would fail here.
for (const role of ["ops", "project-manager"]) {
  const src = read(role);
  assert(
    /\b(gh|glab)\s+(pr|issue|mr)\s+(view|diff|checks|list|comment|merge|create)\b/.test(src),
    `${role}: still told to run the forge CLI directly (it keeps its login)`,
  );
}

console.log(`\nexit ${exit}`);
process.exit(exit);
