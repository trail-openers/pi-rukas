/** The harness' own failures (a fixture it could not write) are fatal to a case
 * rather than counted: a case that cannot build its input has not tested anything,
 * and reporting it as a green run is the worse answer. */
export function harnessFatal(msg: string): never {
  console.error(`✗ HARNESS: ${msg}`);
  process.exit(1);
}

export function writeGenerated(name: string, ms: number, pass = true): string {
  const p = path.join(FIXTURES, name);
  // A fixture the harness could not write means the case has no input at all, and a
  // run over a missing file is the loop's own "no tests" verdict, not a green. Fail
  // the process loudly rather than counting an assertion about nothing.
  try {
    writeFileSync(
      p,
      [
        "#!/usr/bin/env bun",
        `// Generated by test-verify-loop-timing.ts — sleeps ${ms}ms then ${pass ? "passes" : "fails"}.`,
        "// Removed by that test when its case ends; nothing else should depend on it.",
        "// A timer, not a spin: the loop's clock is bash SECONDS, so wall time is all",
        "// the record needs, and a busy wait held a core for every second of it while",
        "// measuring nothing but its own scheduler. The line it prints is a constant for",
        "// the same reason — a caller comparing two runs byte for byte must not be",
        "// comparing the elapsed milliseconds of two independent waits.",
        `await Bun.sleep(${ms});`,
        `console.log(${JSON.stringify(name)} + ": slept");`,
        pass ? "process.exit(0);" : `console.error("✗ ${name}: generated assertion failed"); process.exit(1);`,
        "",
      ].join("\n"),
    );
  } catch (e) {
    harnessFatal(`could not write generated fixture ${p}: ${String(e)}`);
  }
  return p;
}

export function removeGenerated(p: string): void {
  try {
    rmSync(p, { force: true });
  } catch {
    /* a leftover generated fixture is re-written by the next run */
  }
}

export function env(
  extra: Record<string, string | undefined> = {},
): Record<string, string | undefined> {
  // The loop's environment is the host's plus the knobs this file pins. Replacing it
  // wholesale (rather than building a minimal PATH/HOME) is what keeps `bun` findable
  // — the pool starts every job with `bun run`, and a stripped PATH makes the whole
  // run exit 127. The knobs that decide what these cases measure are pinned against
  // an inherited CI value, the same hygiene test-verify-loop-jobs-from-host.ts pins
  // from the other side. The ceiling and its allow-list path are pinned here too:
  // both reach the loop from the environment, so an operator or gate that exports
  // `PI_ENSEMBLE_VERIFY_TIMING_CEILING_S` would silently arm the ceiling inside a
  // test that never asked for it (and point it at a list of someone else's choosing),
  // turning an unrelated verdict change into a puzzling red.
  const base: Record<string, string | undefined> = {
    PI_ENSEMBLE_VERIFY_TEST_JOBS: "1",
    PI_ENSEMBLE_VERIFY_TEST_TIMEOUT_S: "60",
    PI_ENSEMBLE_VERIFY_TIMING_CEILING_S: "",
    TIMING_ALLOWLIST: "",
    // The seam that makes an allow-list read observable from outside the process. It
    // must be absent in every case that does not name it, exactly as the ceiling
    // itself must be — an inherited probe path would have a case assert on a file it
    // never allocated.
    TIMING_ALLOWLIST_PROBE: "",
    // The harness' own arm, read by NOTHING the loop ships. It used to be an
    // environment name the shipped parser read (`TIMING_ALLOWLIST_EAGER`), which let
    // one exported name arm a ceiling on a run nobody asked to grade and fail it with
    // nothing naming why. The arm is now the `arm` argument of `runLoop`, and the name
    // below is scrubbed from every spawn's inherited environment so an operator or a
    // CI step that happens to export it cannot arm a case's run.
    VERIFY_TIMING_TEST_CEILING_S: "",
  };
  return { ...process.env, ...base, ...extra };
}

/**
 * The per-spawn arm's carrier: a `BASH_ENV` FILE the harness writes, which bash
 * sources at the very start of a non-interactive shell — before the loop reads its
 * ceiling knob at all.
 *
 * It is a file, not a shell fragment. Bash takes `BASH_ENV` as a PATH; the
 * `ENV`/`BASH_ENV` FUNCTION hooks are another shell's mechanism and bash demonstrably
 * ignores a function exported under either name, so a file is the only per-spawn seam
 * that reaches the loop's own frame.
 *
 * The arm is handed to the loop through the loop's OWN knob rather than by assigning
 * the parsed variable. That is not a simplification: the pool sources
 * `verify-timing.sh` AFTER this hook has run, so the file's own parse executes again
 * and a bare assignment made here is re-parsed back to zero (observed). Exporting the
 * knob the parse reads is the only shape that survives that second parse — and it is
 * the honest one, because the armed run then takes the same code path an operator-
 * named ceiling takes, which is what makes the canary's probe evidence.
 *
 * Three halves, all load-bearing:
 *
 *   * The name it arms from is pinned EMPTY by `env()` in every spawn, so an ARMED run
 *     is one that passed `arm` to `runLoop`. An ambient value an operator, a CI step or
 *     the suite itself exported therefore arms nothing — no shipped path and no
 *     inherited name forces a ceiling (AC4). The hook then UNSETS the name: the loop
 *     exports `LC_ALL` for the whole run, so an unscrubbed arm would reach every `bun`
 *     test child, where a case could read the very variable that armed its own run —
 *     the shape verify-report-file.sh exists to close. The 1-4 digit gate is the
 *     shipped parse's own, so junk handed to `arm` arms nothing rather than naming a
 *     number the loop would then reject.
 *   * It runs NOTHING unless the name is set. No source, no assignment, no unset, so a
 *     plain run's environment — and its probe file — are exactly what they were before
 *     this existed. `runLoop` does not even pass `BASH_ENV` without an `arm`.
 *   * It is the only place a ceiling is forced, and case 7g's canary is what watches it
 *     fail: point the seeding at a name nothing sets, or drop the export, and the
 *     canary's probe reads empty and the assertion goes RED. A gate nobody has watched
 *     fail proves nothing.
 */
const ARM_HOOK =
  `if [ -n "\${VERIFY_TIMING_TEST_CEILING_S:-}" ] && ` +
  `[[ "\${VERIFY_TIMING_TEST_CEILING_S}" =~ ^[0-9]{1,4}$ ]]; then
` +
  `  export PI_ENSEMBLE_VERIFY_TIMING_CEILING_S="\$VERIFY_TIMING_TEST_CEILING_S"
` +
  `fi
` +
  `unset VERIFY_TIMING_TEST_CEILING_S
`;

/** The scratch file behind `BASH_ENV` for an armed spawn. Written on every armed
 * spawn rather than cached: a fixed path in a shared TMPDIR is a symlink target for
 * another process, and the write is one syscall against a case that runs a whole
 * loop. Nothing removes it — a scratch file in TMPDIR is reaped with TMPDIR, the same
 * convention every temp allow-list in this file follows. */
function armHookPath(): string {
  const dir = mkdtempDirSync(path.join(tmpdir(), "pi-2449-arm-"));
  const p = path.join(dir, "seed.sh");
  try {
    writeFileSync(p, ARM_HOOK, { mode: 0o600 });
  } catch (e) {
    harnessFatal(`could not write the timing arm hook at ${p}: ${String(e)}`);
  }
  return p;
}

/**
 * The ONE place a ceiling is forced for a test, as the child sees it — for
 * test-verify-timing-ceiling.ts case 7g's canary, which asserts this is NON-EMPTY on
 * an armed spawn and would otherwise have no way to tell a hook that ran from one that
 * never fired. A run whose canary cannot be observed failing is an assertion about
 * nothing, and the harness is the only party that knows whether it armed the spawn.
 */
export const ARM_HOOK_BODY = ARM_HOOK;

/** Per-spawn arm for `runLoop`: the ceiling a case forces on a spawn whose operator-
 * facing knob stayed off. Harness-only by construction — the shipped loop parses no
 * such name, and the harness pins it empty so an inherited value cannot arm a run. */
export type TimingArm = { ceiling: string };

export function runLoop(
  files: string[],
  extraEnv: Record<string, string | undefined> = {},
  // `--digest` is the loop's FIRST argument, before the file list — so it is passed
  // here rather than smuggled through the environment, where the loop would never
  // see it and the case would quietly test normal mode twice.
  prefix: string[] = [],
  // The mutant twin, per spawn rather than per environment (see `TimingArm`). Omit it
  // and the loop is spawned with exactly the environment it has always had — no
  // `BASH_ENV`, no hook file, no arm.
  arm?: TimingArm,
): { status: number; stdout: string; stderr: string } {
  const armed: Record<string, string | undefined> = {};
  if (arm !== undefined) {
    if (!/^[0-9]{1,4}$/.test(arm.ceiling)) {
      harnessFatal(`timing arm ceiling must be 1-4 digits, got ${JSON.stringify(arm.ceiling)}`);
    }
    armed.VERIFY_TIMING_TEST_CEILING_S = arm.ceiling;
    armed.BASH_ENV = armHookPath();
  }
  const r = spawnSync("bash", [LOOP, ...prefix, ...files], {
    // `extension/`, the directory every other verify-loop test invokes the loop from
    // (see runLoopEnv in verify-loop-lib.ts): the loop resolves its own lib/ halves by
    // BASH_SOURCE, but the per-test watchdog runs the command the loop builds relative
    // to the working directory.
    cwd: REPO,
    encoding: "utf8",
    timeout: 240_000,
    env: env({ ...extraEnv, ...armed }),
  });
  return { status: r.status ?? -1, stdout: r.stdout ?? "", stderr: r.stderr ?? "" };
}

export const TIME_RE = /^TIME (\d+) (.+)$/;
export const HEADER_RE = /^SLOWEST: top (\d+) of (\d+) \(N=(\d+)\)$/;
export const TOTAL_RE = /^TOTAL wall (\d+)  sum (\d+)  max (\d+)$/;
/** The ceiling line's shape, pinned exactly (R9): `CEILING: <secs>s <file> (ceiling <N>s)`. */
export const CEILING_RE = /^CEILING: (\d+)s (.+) \(ceiling (\d+)s\)$/;

/**
 * The one filter that recognises a line the timing feature prints — a `TIME` row, the
 * block's header, a block row, TOTAL, or `CEILING:`. Two test files strip these before
 * comparing whole channels (case 7f of test-verify-timing-ceiling.ts and case 8 of
 * test-verify-timing-ceiling-channels.ts) and both MUST strip one set, or "the off path
 * changed nothing" becomes two claims that can drift apart — a shape the harness'
 * `timingOutput` cannot serve, since it returns the lines it RECOGNISES and so compares
 * two filtered sets, passing on streams differing anywhere else.
 */
export function isTimingLine(l: string): boolean {
  return TIME_RE.test(l) || HEADER_RE.test(l) || TOTAL_RE.test(l) || CEILING_RE.test(l);
}

/** A whole channel with every timing line removed — the comparison both off-path cases
 * actually make. Two busy-wait processes can only ever agree modulo their measured
 * seconds (the ±50% swing the ceiling test's header pins), which is what `TOTAL` sums. */
export function stripTiming(s: string): string {
  return s
    .split("\n")
    .filter((l) => !isTimingLine(l))
    .join("\n");
}

/** Every `CEILING:` line on a channel, with its fields parsed. */
export function ceilingLines(output: string): { secs: number; file: string; ceiling: number }[] {
  const rows: { secs: number; file: string; ceiling: number }[] = [];
  for (const line of output.split("\n")) {
    const m = CEILING_RE.exec(line);
    if (m) rows.push({ secs: Number(m[1]), file: m[2] ?? "", ceiling: Number(m[3]) });
  }
  return rows;
}

export type Row = { secs: number; file: string };

/** The per-file lines, in the order printed — the summary block's rows excluded.
 * Both shapes start `TIME `; the block's rows are those after its header, so the
 * record is every `TIME ` line BEFORE the header. */
export function timeLines(stdout: string): Row[] {
  const rows: Row[] = [];
  for (const line of stdout.split("\n")) {
    if (HEADER_RE.test(line)) break;
    const m = TIME_RE.exec(line);
    if (m) rows.push({ secs: Number(m[1]), file: m[2] ?? "" });
  }
  return rows;
}

export function summaryHeader(stdout: string): { shown: number; total: number; n: number } | null {
  for (const line of stdout.split("\n")) {
    const m = HEADER_RE.exec(line);
    if (m) return { shown: Number(m[1]), total: Number(m[2]), n: Number(m[3]) };
  }
  return null;
}

/** The block's rows: `<secs> <file>  <outcome>` after the header, before TOTAL. */
export function blockRows(stdout: string): Row[] {
  const lines = stdout.split("\n");
  const start = lines.findIndex((l) => HEADER_RE.test(l));
  if (start === -1) return [];
  const rows: Row[] = [];
  for (let i = start + 1; i < lines.length; i++) {
    if (TOTAL_RE.test(lines[i] ?? "")) break;
    const m = TIME_RE.exec(lines[i] ?? "");
    if (!m) continue;
    const rest = m[2] ?? "";
    // The block row is the per-file line plus its outcome, which is one of the
    // labels the loop writes and never contains a double space; a test path may,
    // so the split is on the LAST one.
    const cut = rest.lastIndexOf("  ");
    if (cut <= 0) continue;
    rows.push({ secs: Number(m[1]), file: rest.slice(0, cut) });
  }
  return rows;
}

export function outcomeOf(stdout: string, file: string): string {
  const lines = stdout.split("\n");
  const start = lines.findIndex((l) => HEADER_RE.test(l));
  if (start === -1) return "";
  for (let i = start + 1; i < lines.length; i++) {
    const line = lines[i] ?? "";
    if (TOTAL_RE.test(line)) break;
    const m = TIME_RE.exec(line);
    if (!m) continue;
    const rest = m[2] ?? "";
    const cut = rest.lastIndexOf("  ");
    if (cut <= 0) continue;
    if (rest.slice(0, cut) === file) return rest.slice(cut + 2);
  }
  return "";
}

export function totalLine(stdout: string): string {
  for (const line of stdout.split("\n")) if (TOTAL_RE.test(line)) return line;
  return "";
}

/** Every timing line on the channel the feature prints on, for the byte-for-byte
 * comparisons: the record, the block rows, the header and TOTAL together, and the
 * ceiling lines — a line that survived an "off" run would otherwise slip through
 * the comparison as an unrecognised line rather than as a timing leak. */
export function timingOutput(stdout: string): string[] {
  return stdout.split("\n").filter(
    (l) => TIME_RE.test(l) || HEADER_RE.test(l) || TOTAL_RE.test(l) || CEILING_RE.test(l),
  );
}

/** Allocate a unique scratch directory in one non-racing step. The suite runs
 * tests in parallel, so `mkdtempSync`'s random suffix alone is not enough to make
 * a retried allocation safe across sibling processes. */
export function mkdtempDirSync(prefix: string): string {
  let n = 0;
  while (n++ < 64) {
    const p = `${prefix}${Math.random().toString(36).slice(2, 10)}`;
    try {
      mkdirSync(p, { recursive: false, mode: 0o700 });
      return p;
    } catch {
      /* taken by a sibling run; try another name */
    }
  }
  harnessFatal(`could not allocate a scratch dir from ${prefix}`);
  return `${prefix}unreachable`;
}

/**
 * Write a temporary allow-list naming the given `file` keys (paths relative to
 * `extension/`, the key the loop matches on — R4) and return the value to hand the
 * loop as `TIMING_ALLOWLIST`.
 *
 * The list is a temp file rather than an edit to the committed one: the suite runs
 * tests in parallel, so a mutation with a `finally` is a race another test could
 * read, and a killed process would leave the shipped exemptions changed. The loop
 * reads its path from the environment for exactly this reason.
 */
export function writeAllowlist(
  entries: { file: string; seconds: number }[],
  baselineCount?: number,
): string {
  const dir = mkdtempDirSync(path.join(tmpdir(), "pi-ens-allowlist-"));
  const p = path.join(dir, "timing-allowlist.json");
  try {
    writeFileSync(
      p,
      JSON.stringify(
        baselineCount === undefined ? { entries } : { baseline_count: baselineCount, entries },
        null,
        2,
      ),
    );
  } catch (e) {
    harnessFatal(`could not write a temporary allow-list at ${p}: ${String(e)}`);
  }
  return p;
}

/** Remove a temporary allow-list dir from `writeAllowlist`. */
export function removeAllowlist(p: string): void {
  try {
    rmSync(path.dirname(p), { recursive: true, force: true });
  } catch {
    /* a leftover temp dir is reaped with TMPDIR */
  }
}

