#!/usr/bin/env bun
/**
 * #1156 — the developer ROLE PROMPT carries the same two rules the `/work`
 * develop prompt carries.
 *
 * The develop-step prompt (`inlineDevelopPrompt`) is only half the surface: a
 * hand-run `@developer` dispatch, or a lens-fix developer, reads the assembled
 * role prompt from `agents-base/developer.md`. Measured harm behind both
 * rules: on a `/work` fan-out developers ran the FULL offline suite in every
 * worktree with no bound (one stuck ~20 min on a single suite call) while the
 * driver's own verify ran the whole thing again; and on PR #1150 a developer
 * met the 500-line cap by shortening pre-existing comments — 109 lines, then
 * 27 — which cost extra review rounds.
 *
 * Asserted against the SOURCE markdown, not `dist/`: `dist/prompts/standard/`
 * is gitignored and regenerated by `bun run build`, so the source is the
 * thing a contributor commits and the thing that can drift.
 */

import { readFileSync } from "node:fs";
import path from "node:path";
import { suiteTimeoutSeconds } from "../src/work-driver-verify-fast.ts";
import { withEnv } from "./lib/env-scope.ts";
import { assertSuiteBoundDerivation } from "./lib/developer-test-scope.ts";

const KNOB = "PI_ENSEMBLE_TOOL_INACTIVITY_TIMEOUT_MS";

/**
 * Run `body` with the watchdog knob pinned to `ms` (deleted when undefined).
 * Delegates to the shared `withEnv` rather than keeping a local copy of the
 * save/restore dance — same semantics, one implementation, no fork to drift.
 *
 * The knob MUST be pinned for every assertion that compares the doc against a
 * derived number: an ambient `PI_ENSEMBLE_TOOL_INACTIVITY_TIMEOUT_MS` in the
 * operator's shell otherwise moves `suiteTimeoutSeconds()` out from under the
 * literal 1200 hardcoded in `developer.md`, and this file fails on a machine
 * -wide env var nobody changed.
 */
async function withWatchdog(ms: string | undefined, body: () => Promise<void>): Promise<void> {
  await withEnv({ [KNOB]: ms }, body);
}

let exit = 0;
function assert(cond: boolean, msg: string) {
  if (cond) console.log(`✓ ${msg}`);
  else {
    console.error(`✗ ${msg}`);
    exit = 1;
  }
}

const ROOT = path.resolve(import.meta.dirname, "..", "..");
const DOC = path.join(ROOT, "agents-base", "developer.md");

// No existsSync guard: a missing or unreadable doc is the failure this test
// exists to catch, and `readFileSync` naming the path and the errno is a
// better report than an assertion that a file is empty.
const src = readFileSync(DOC, "utf8");
assert(src.length > 0, `non-vacuity: ${path.relative(ROOT, DOC)} is readable`);

// ------------------------------------------------ test-scope + suite timeout
//
// Every assertion that compares the doc against a DERIVED number runs inside
// the watchdog guard, and SUITE_SECONDS is computed THERE rather than at module
// scope — a module-scope const reads the ambient env at import time, which is
// precisely the value an operator may have set to something else.
await withWatchdog(undefined, async () => {
  const SUITE_SECONDS = suiteTimeoutSeconds();

  assert(
    /Do NOT run the full test suite/i.test(src),
    "#1156: the role prompt forbids running the full suite",
  );
  assert(
    /smoke tests? for the files you changed/i.test(src),
    "#1156: the role prompt scopes the developer to the smoke tests for files it changed",
  );
  assert(
    /typecheck and lint/i.test(src),
    "#1156: typecheck and lint stay in the developer's own scope",
  );
  assert(
    /driver.{0,40}runs? (it|the full suite)|driver.{0,20}verify runs? it once/i.test(src),
    "#1156: the role prompt says the driver runs the full suite, so skipping it is not skipping verification",
  );
  assert(
    src.includes(`timeout ${SUITE_SECONDS}`),
    `#1156: every suite command carries \`timeout ${SUITE_SECONDS}\` (derived from the watchdog, so code and doctrine cannot drift apart)`,
  );
  assert(
    /timeout 1200/.test(src),
    "#1156: the literal 'timeout 1200' the issue names is in the role prompt at the default watchdog",
  );

  // `timeout` is GNU coreutils and macOS ships none by default — but whether a
  // binary exists is a fact about the machine the child is on, so the role
  // prompt must make the child LOOK rather than rest on a platform claim. A
  // prompt that asserts "macOS ships none" tells a child in a Linux container,
  // a CI image, or a Mac with coreutils installed to run unbounded for nothing.
  assert(
    // Mutation anchor: the EXECUTABLE probe line in the code block, not the
    // prose that mentions the same command. Matching the prose alone would let
    // the code block regress to the multi-argument bashism while this assertion
    // stayed green off the explanatory sentence beside it.
    /^command -v timeout \|\| command -v gtimeout/m.test(src) &&
      /probe for a timeout binary/i.test(src),
    "#1156 fallback: the role prompt tells the child to PROBE for a timeout binary with the POSIX `command -v X || command -v Y` form (imperative prose + the probe command in the code block), not a multi-argument bashism whose exit status the spec leaves undefined",
  );
  assert(
    /gtimeout/i.test(src),
    "#1156 fallback: gtimeout (Homebrew coreutils) is named as the same tool",
  );
  assert(
    /only where the probe prints nothing/i.test(src),
    "#1156 fallback: running bare is gated on the probe finding neither binary, not on a platform guess",
  );
  assert(
    /run the command bare/i.test(src),
    "#1156 fallback: with no `timeout` the command runs bare",
  );
  assert(
    /stay under the tool watchdog|under the tool watchdog/i.test(src),
    "#1156 fallback: the bare-run fallback is bounded by the tool watchdog, not left unbounded",
  );
  assert(
    /PI_ENSEMBLE_TOOL_INACTIVITY_TIMEOUT_MS/.test(src),
    "#1156 fallback: the watchdog bound is named by its knob, so the two timeout rules resolve to one",
  );
  // The doctrine number is pinned here rather than left as prose a reader
  // trusts. `developer.md` hardcodes the literal; this is the only thing
  // standing between that literal and the derivation it is supposed to
  // be. Drift is silent otherwise: the derivation moving leaves stale doctrine
  // promising a bound the harness no longer gives, and the doctrine moving
  // promises a bound LONGER than the watchdog, which is not a bound.
  const doctrineNumbers = [...src.matchAll(/timeout (\d+) /g)].map((m) => m[1]);
  assert(
    doctrineNumbers.length > 0 && doctrineNumbers.every((n) => n === String(SUITE_SECONDS)),
    `#1156: every \`timeout <n>\` in the role prompt equals suiteTimeoutSeconds() (${SUITE_SECONDS}) at the default watchdog — the prose cannot drift from the derivation`,
  );
});
// Mutation anchor: a heading that has gone missing makes indexOf return -1,
// which silently empties the slice and the regex below fails on "" with a
// message that blames the prose rather than the heading.
function between(start: string, end: string): string {
  const from = src.indexOf(start);
  if (from === -1) throw new Error(`missing heading anchor "${start}" in ${DOC}`);
  const to = src.indexOf(end, from);
  if (to === -1) throw new Error(`missing heading anchor "${end}" after "${start}" in ${DOC}`);
  return src.slice(from, to);
}
assert(
  /Git safety/i.test(src) &&
    /(same bound|one rule|not two unrelated|same rule)/i.test(
      between("Scope your own testing", "Size caps"),
    ),
  "#1156 fallback: the section points at the existing watchdog paragraph so the two timeout rules do not read as unrelated",
);

// ------------------------------------------- the bound follows the watchdog

assertSuiteBoundDerivation(assert);

// ------------------------------------------------ size cap: split, don't shorten

assert(
  /split it along a natural seam|split files/i.test(src),
  "#1156: the role prompt tells the developer to split an oversized file",
);
assert(
  /never (meet a size cap by )?shorten|never shorten/i.test(src),
  "#1156: the role prompt forbids meeting a size cap by shortening comments",
);
assert(
  /pre-existing comments/i.test(src),
  "#1156: the prohibition names pre-existing comments specifically (the PR #1150 failure)",
);

console.log(`\nexit ${exit}`);
process.exit(exit);
