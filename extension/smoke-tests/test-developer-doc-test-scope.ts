#!/usr/bin/env bun
/**
 * #1156 — the developer ROLE PROMPT carries the same two rules the `/work`
 * develop prompt carries.
 *
 * The develop-step prompt (`inlineDevelopPrompt`) is only half the surface: a
 * hand-run `@developer` dispatch, or a lens-fix developer, reads the assembled
 * role prompt from `agents-base/developer.md`. Measured harm behind both
 * rules: on a `/work` fan-out developers ran the FULL offline suite in every
 * worktree with no bound (one stuck ~20 min on a single suite call) while the
 * driver's own verify ran the whole thing again; and on PR #1150 a developer
 * met the 500-line cap by shortening pre-existing comments — 109 lines, then
 * 27 — which cost extra review rounds.
 *
 * Asserted against the SOURCE markdown, not `dist/`: `dist/prompts/standard/`
 * is gitignored and regenerated by `bun run build`, so the source is the
 * thing a contributor commits and the thing that can drift.
 */

import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { SUITE_TIMEOUT_SECONDS } from "../src/work-driver-verify-fast.ts";

let exit = 0;
function assert(cond: boolean, msg: string) {
  if (cond) console.log(`✓ ${msg}`);
  else {
    console.error(`✗ ${msg}`);
    exit = 1;
  }
}

const ROOT = path.resolve(import.meta.dirname, "..", "..");
const DOC = path.join(ROOT, "agents-base", "developer.md");

const src = existsSync(DOC) ? readFileSync(DOC, "utf8") : "";
assert(src.length > 0, `non-vacuity: ${path.relative(ROOT, DOC)} is readable`);

// ------------------------------------------------ test-scope + suite timeout

assert(
  /Do NOT run the full test suite/i.test(src),
  "#1156: the role prompt forbids running the full suite",
);
assert(
  /smoke tests? for the files you changed/i.test(src),
  "#1156: the role prompt scopes the developer to the smoke tests for files it changed",
);
assert(
  /typecheck and lint/i.test(src),
  "#1156: typecheck and lint stay in the developer's own scope",
);
assert(
  /driver.{0,40}runs? (it|the full suite)|driver.{0,20}verify runs? it once/i.test(src),
  "#1156: the role prompt says the driver runs the full suite, so skipping it is not skipping verification",
);
assert(
  src.includes(`timeout ${SUITE_TIMEOUT_SECONDS}`),
  `#1156: every suite command carries \`timeout ${SUITE_TIMEOUT_SECONDS}\` (exported constant, so code and doctrine cannot drift apart)`,
);
assert(
  /timeout 1200/.test(src),
  "#1156: the literal 'timeout 1200' the issue names is in the role prompt",
);

// `timeout` is GNU coreutils — macOS ships none, and this repo's own
// smoke-tests/lib/verify-kill.sh deliberately avoids it for the same reason.
// A role prompt that mandates the binary is wrong on the dev machine.
assert(
  /macOS ships none|macOS has no .{0,10}timeout/i.test(src),
  "#1156 fallback: the role prompt says macOS has no `timeout`",
);
assert(
  /gtimeout/i.test(src),
  "#1156 fallback: gtimeout (Homebrew coreutils) is named as the same tool",
);
assert(
  /run the command bare/i.test(src),
  "#1156 fallback: with no `timeout` the command runs bare",
);
assert(
  /stay under the tool watchdog|under the tool watchdog/i.test(src),
  "#1156 fallback: the bare-run fallback is bounded by the tool watchdog, not left unbounded",
);
assert(
  /PI_ENSEMBLE_TOOL_INACTIVITY_TIMEOUT_MS/.test(src),
  "#1156 fallback: the watchdog bound is named by its knob, so the two timeout rules resolve to one",
);
assert(
  /Git safety/i.test(src) &&
    /(same bound|one rule|not two unrelated|same rule)/i.test(
      src.slice(src.indexOf("Scope your own testing"), src.indexOf("Size caps")),
    ),
  "#1156 fallback: the section points at the existing watchdog paragraph so the two timeout rules do not read as unrelated",
);

// ------------------------------------------------ size cap: split, don't shorten

assert(
  /split it along a natural seam|split files/i.test(src),
  "#1156: the role prompt tells the developer to split an oversized file",
);
assert(
  /never (meet a size cap by )?shorten|never shorten/i.test(src),
  "#1156: the role prompt forbids meeting a size cap by shortening comments",
);
assert(
  /pre-existing comments/i.test(src),
  "#1156: the prohibition names pre-existing comments specifically (the PR #1150 failure)",
);

console.log(`\nexit ${exit}`);
process.exit(exit);
