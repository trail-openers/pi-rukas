/**
 * forge-read-auth — the shared authentication half of the `forge_read` channel
 * (#2160 adversarial round 1).
 *
 * The broker socket answers CONTENT with the PARENT's credential, and the child
 * decides whether to trust the bytes by checking that they came from the process
 * that owns the socket. A socket path alone is not that check: a path is a name,
 * and a name in a temp root can be occupied by someone else — an inherited or
 * stale `PI_ENSEMBLE_FORGE_READ_SOCKET` makes the child send its reads to, and
 * trust the answers of, whatever process listens there. So the spawn layer mints
 * a fresh secret per child (this file's `newForgeReadSecret`) and both halves
 * prove they hold it:
 *
 *   child → parent   HMAC(secret, `${nonce}\n${request-line}`)   — `auth` field
 *   parent → child   HMAC(secret, `${nonce}\n${reply-line}`)      — `mac` field
 *
 * The nonce is fresh per request, generated by the CHILD, and the reply is
 * covered by the nonce the child chose: a listener that merely holds the socket
 * path can neither make a request the parent will act on nor produce a reply the
 * child will read as data. Both directions fail the same way — a refusal that
 * carries no bytes — which is the only shape an unauthenticated answer may take.
 *
 * What the MAC binds:
 *   - the nonce, so a captured reply cannot be replayed on another request;
 *   - the whole serialised reply line, so the bytes AND the verdict (`ok`,
 *     `reason`) are covered — a flipped `ok` or an edited `reason` is a
 *     mismatch;
 *   - the secret, which never crosses the socket in either direction.
 *
 * Fail-closed in both directions and on both malformed inputs: an `auth`/`mac`
 * that is not a 64-char lowercase hex string is treated as ABSENT, never
 * compared, so a caller-supplied value can never `===` its way past a check.
 * `timingSafeEqual` requires equal lengths, which the shape check guarantees
 * before the comparison (a length mismatch is a refusal, not an exception).
 *
 * The secret never appears in a log, a trace, an error message or a transcript:
 * nothing here returns, prints, or embeds it, and every refusal this module
 * produces names a category (`unauthenticated request`, `unverified reply`) and
 * nothing about the key. Keep it that way when adding a message.
 */

import { createHmac, randomBytes, timingSafeEqual } from "node:crypto";
import type { ForgeReadRequest, ForgeReadResponse } from "./forge-read-tool.ts";

/** The env the child reads the parent's broker secret from, beside the socket path. */
export const FORGE_READ_SECRET_ENV = "PI_ENSEMBLE_FORGE_READ_SECRET";

/** Byte length of the per-child secret (hex-encoded on the wire and in the env). */
export const FORGE_READ_SECRET_BYTES = 32;

/** A shape-checkable MAC: 64 lowercase hex characters, and nothing else. */
const HEX_MAC = /^[0-9a-f]{64}$/;

/**
 * Mint one per-child broker secret. Called by the spawn layer at the instant it
 * starts the child's broker, so no two children of one parent ever share a key
 * and a key never outlives the dispatch that made it.
 */
export function newForgeReadSecret(): string {
  return randomBytes(FORGE_READ_SECRET_BYTES).toString("hex");
}

/**
 * The MAC over one nonce and one wire line. The newline between them is part of
 * the pre-image so a nonce cannot be extended into the line (and vice versa)
 * without changing the digest.
 */
export function forgeReadMac(secret: string, nonce: string, line: string): string {
  return createHmac("sha256", secret).update(`${nonce}\n${line}`).digest("hex");
}

/**
 * Is `candidate` the MAC for this `secret`/`nonce`/`line`? Anything that is not
 * a 64-char lowercase hex string is a refusal, never a comparison; the digest
 * itself is compared in constant time.
 */
export function verifyForgeReadMac(
  secret: string,
  nonce: string,
  line: string,
  candidate: unknown,
): boolean {
  if (typeof candidate !== "string" || !HEX_MAC.test(candidate)) return false;
  const expected = forgeReadMac(secret, nonce, line);
  return timingSafeEqual(Buffer.from(expected, "utf8"), Buffer.from(candidate, "utf8"));
}

/**
 * A fresh per-request nonce. Generated by the CHILD for a request and by the
 * PARENT for a reply; 16 random bytes is far past any collision concern for keys
 * that live as long as one dispatch.
 */
export function newForgeReadNonce(): string {
  return randomBytes(16).toString("hex");
}

/**
 * The envelope the CHILD puts on the socket: its own identity fields, and the
 * `payload` the proof covers — the declared read, sent only inside that proof.
 *
 * Separating the two is what lets the parent prove a request without the child
 * ever putting a verb on the wire. `auth` and `mac` are excluded from what they
 * sign (a field cannot cover its own bytes) on both sides, and neither key is
 * ever a field the parent's parser can reach: `parseForgeReadRequest` whitelists
 * the declared read fields, so `nonce`/`auth` are dropped before the executor
 * sees the object.
 */
export interface ForgeReadAuthedRequest {
  type?: unknown;
  nonce?: unknown;
  payload?: Partial<ForgeReadRequest>;
  auth?: unknown;
}

/**
 * The envelope the PARENT puts on the socket: the answer, the reply's own nonce,
 * and `echo` — the request's nonce, so the proof binds which read this answers.
 */
export type ForgeReadAuthedResponse = ForgeReadResponse & {
  nonce?: string;
  echo?: string;
  mac?: string;
};

/**
 * The two messages a request must carry, and the reason a request without them
 * is refused. `undefined` means the request may be authenticated and served.
 *
 * Kept separate from the transport so the rule ("a nonce, and a proof over this
 * nonce and this line") is one testable predicate rather than a branch buried in
 * the socket handler.
 */
export function missingRequestAuth(nonce: unknown, auth: unknown): string | undefined {
  if (typeof nonce !== "string" || nonce.length === 0) {
    return 'forge_read: request carries no "nonce"';
  }
  if (typeof auth !== "string" || !HEX_MAC.test(auth)) {
    return "forge_read: request carries no valid proof";
  }
  return undefined;
}
