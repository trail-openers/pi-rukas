/**
 * public-hygiene-gh-flags — the per-(noun, verb) gh publish flag tables
 * (#1792 final round), split out of `public-hygiene-verbs.ts` along the seam
 * AGENTS.md §12 asks for: this module owns WHICH flag means WHAT for a given
 * `gh <noun> <verb>`, the verbs module owns reading the operand and building the
 * verdict.
 *
 * ## Why the tables are built at module load
 *
 * `scanGhPublish` runs once per command segment, per tool_call. It used to
 * derive its two tables there, with three `Object.fromEntries(Object.entries(…)
 * .filter(…))` chains — a dozen object allocations and a full key walk per
 * publish, to produce one of a handful of answers that never change. The answer
 * is data, so it is computed once, at load, and the reader below is a lookup.
 *
 * ## The table is EXPANSION, not a second rule
 *
 * `buildGhFlagTables` is the derived-from-source rule and nothing else: it takes
 * the source flag set and the same role exclusions, and evaluates them for every
 * (noun, verb) pair the verb set admits. The literal tables were generated by
 * running it and pasting the output, and the `test-public-hygiene-gh-flags.ts`
 * canary re-derives every pair from these exports and fails on any difference —
 * so a hand-edit that drifts from the rule it claims to encode is caught rather
 * than shipped.
 *
 * ## The one rule a reader of this file must not lose
 *
 * `-n` and `-F` are the whole reason there are two tables per pair rather than
 * one pair of globals:
 *
 * - `-n` is `gh release create`'s notes TEXT flag and `gh release edit`'s notes
 *   FILE flag, and `gh issue`'s "no-body" switch. It is therefore a text flag
 *   for `release create`, a file flag for `release edit`, and neither for an
 *   issue or a pr — where reading it as prose would refuse a boolean switch's
 *   own name.
 * - `-F` is `gh issue|pr create`'s `--body-file` and `gh release`'s
 *   `--notes-file` short form for BOTH create and edit (gh 2.102.0:
 *   `-F, --notes-file file`, `-` meaning stdin). A word claimed by neither
 *   table publishes its notes unchecked; a word claimed by BOTH reads a PATH as
 *   prose and never opens the file.
 *
 * Each table is therefore keyed by the (noun, verb-role) pair the reader asks
 * about, and the pair is the only thing that settles which reader owns a word.
 */

/** A flag → the location its operand publishes to ("body", "release notes", …). */
export type GhFlagTable = Readonly<Record<string, string>>;

/** The two readers a publish needs: which words are FILES, which are TEXT. */
export interface GhFlagPair {
  file: GhFlagTable;
  text: GhFlagTable;
}

/**
 * The keys of {@link GH_PUBLISH_FLAGS}: `noun` for `create`/`edit`/`comment`,
 * `release-create` and `release-edit` for the two release verbs, whose `-n`
 * differs. `ghPublishNoun` resolves the key once and hands it to the reader.
 */
export function ghFlagKey(noun: string, verb: string): string {
  return noun === "release" ? `${noun}-${verb}` : noun;
}

/**
 * The source flag set: every gh word that can carry published prose, with its
 * role. `role` is the exclusion the derived rule filters on — `notes-text` and
 * `message` are meaningless for an issue or a pr, where `-n` is a switch and
 * `--subject` is not a gh flag at all.
 */
const GH_TEXT_SOURCE: ReadonlyArray<readonly [string, string, string]> = [
  ["--title", "title", "title"],
  ["-t", "title", "title"],
  ["--body", "body", "body"],
  ["-b", "body", "body"],
  ["--notes", "release notes", "notes-text"],
  // `-n` is `gh release create`'s notes TEXT flag and `gh issue create`'s
  // "no-body" switch. It is read ONLY for the release noun, where it is the
  // notes, and never for an issue or a pr, where treating it as text would
  // refuse a boolean switch's own name.
  ["-n", "release notes", "notes-text"],
  ["--subject", "commit message", "message"],
];

/** The source file-flag set, same shape: flag → location, plus its role.
 *
 * The role names what the flag IS, not which noun uses it — the noun decides
 * which role applies and the location names what it publishes there. `-F` is
 * one flag with one role that spans both nouns (`--body-file` for issue/pr,
 * `--notes-file` for release), which is why it is a single entry whose location
 * the rule picks per noun rather than two entries a filter could drop one of.
 */
const GH_FILE_SOURCE: ReadonlyArray<readonly [string, string, string]> = [
  ["--body-file", "body", "body-file"],
  ["--notes-file", "release notes", "notes-file"],
  ["-n", "release notes", "notes-file"],
  // `-F` LAST, exactly as the pre-extraction filter chain left it: that code
  // started from `{"--notes-file":…}` (which the old release table already held)
  // and the `filter(flag => flag !== "-n")` chain appended `-F` after it for
  // create, while edit took the unfiltered object (`--notes-file`, `-n`, `-F`).
  // Key order is observable — `fileFlagOf` returns the FIRST matching key and
  // `flagValueOf` reads the value from THAT flag — so `-Fnotes.md` is read as
  // `notes.md` under this order and as `-notes.md` under the other, which is
  // exactly what the roots test and the 1 MiB bound notice. The canary compares
  // order for this reason, so the source order is the behaviour, not a detail.
  ["-F", "any-file", "short-file"],
];

/**
 * The derived rule, kept in source so the canary can re-derive the literals
 * below from it rather than trusting them. `noun` decides the body-vs-notes
 * flags; `notesIsFile` is what `gh release edit` does to `-n`.
 *
 * The locations are the same strings the pre-extraction code produced: the
 * body flags for issue/pr, `release notes` for every release file and text
 * operand, and `title`/`body`/`commit message` for the text flags.
 *
 * `-F` is the short form of `--body-file` for `gh issue|pr` and of
 * `--notes-file` for BOTH `gh release create` and `gh release edit` (gh
 * 2.102.0: `-F, --notes-file file`, `-` meaning stdin). Without it a notes file
 * named by the short flag matched no reader at all — neither the file table nor
 * the text table — and published unread (#1792). It is therefore ONE source entry
 * whose location the noun decides, not two entries a filter could drop.
 *
 * KEY ORDER is preserved from the source lists on purpose: `fileFlagOf` walks a
 * table's keys in order and returns the first match, so the order the
 * pre-extraction filter chain produced is observable, and the canary compares it
 * rather than normalising it away.
 */
export function buildGhFlagTables(noun: string, notesIsFile: boolean): GhFlagPair {
  const isRelease = noun === "release";
  const text: Record<string, string> = {};
  for (const [flag, location, role] of GH_TEXT_SOURCE) {
    if (role === "notes-text" && !isRelease) continue;
    if (role === "message" && !isRelease) continue;
    // `gh release edit`'s `-n` names a FILE, so the text reader must not claim
    // it; `--notes-file` is likewise never prose.
    if (notesIsFile && (flag === "-n" || flag === "--notes-file")) continue;
    text[flag] = location;
  }
  const file: Record<string, string> = {};
  for (const [flag, location, role] of GH_FILE_SOURCE) {
    if (role === "body-file" && isRelease) continue;
    if (role === "notes-file" && !isRelease) continue;
    // `-n` is a file flag only for `release edit`; for create it is the notes
    // text, and the text table owns it.
    if (flag === "-n" && !notesIsFile) continue;
    // The shared short form publishes whatever this noun's file flags publish.
    file[flag] = location === "any-file" ? (isRelease ? "release notes" : "body") : location;
  }
  return { file, text };
}

/**
 * The literal tables — one entry per (noun, verb-role) pair `ghPublishNoun`
 * admits, generated by {@link buildGhFlagTables} and pinned against it by
 * `test-public-hygiene-gh-flags.ts`. A lookup, not a filter chain: this is what
 * `scanGhPublish` reads on every publish.
 */
export const GH_PUBLISH_FLAGS: Readonly<Record<string, GhFlagPair>> = Object.freeze({
  issue: Object.freeze({
    file: Object.freeze({ "--body-file": "body", "-F": "body" }),
    text: Object.freeze({ "--title": "title", "-t": "title", "--body": "body", "-b": "body" }),
  }),
  pr: Object.freeze({
    file: Object.freeze({ "--body-file": "body", "-F": "body" }),
    text: Object.freeze({ "--title": "title", "-t": "title", "--body": "body", "-b": "body" }),
  }),
  // `release create`: `-n` is the NOTES TEXT, so it sits in `text` and is
  // deliberately absent from `file`.
  // `release create`: `-F` sits after `--notes-file` — the order the
  // pre-extraction filter chain produced, which `fileFlagOf`'s first-match loop
  // can make observable, so the canary compares it rather than normalising it.
  "release-create": Object.freeze({
    file: Object.freeze({ "--notes-file": "release notes", "-F": "release notes" }),
    text: Object.freeze({
      "--title": "title",
      "-t": "title",
      "--body": "body",
      "-b": "body",
      "--notes": "release notes",
      "-n": "release notes",
      "--subject": "commit message",
    }),
  }),
  // `release edit`: `-n` is the NOTES FILE, so the roles are swapped — it is in
  // `file` and out of `text`, which is the single difference between these two
  // entries and the reason one pair per verb is needed rather than one pair per
  // noun.
  "release-edit": Object.freeze({
    file: Object.freeze({
      "--notes-file": "release notes",
      "-n": "release notes",
      "-F": "release notes",
    }),
    text: Object.freeze({
      "--title": "title",
      "-t": "title",
      "--body": "body",
      "-b": "body",
      "--notes": "release notes",
      "--subject": "commit message",
    }),
  }),
});
