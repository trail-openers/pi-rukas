/**
 * work-driver-verify-always-run — #1647: the smoke tests that run on EVERY
 * develop verify, whatever the diff touched.
 *
 * A test that reads repository source or configuration AS TEXT depends on files
 * no import graph shows: it opens `src/x.ts` by name, or walks the directory.
 * A selection built from imports would never run it for a change to the file
 * it reads, so it is listed here and runs always. The list is enumerated, not
 * inferred at run time, so an entry that goes missing is a reviewable diff.
 *
 * `textReadingTests` is the detector the completeness smoke test
 * (`test-verify-select-always-run.ts`) runs against the tree. It is
 * deliberately conservative: a file that makes a read call AND names a
 * repository segment is a reader, so a fixture that writes and reads back a
 * `src/` file is listed too. Each extra entry costs one test per develop round;
 * a missed reader is a gate that never looked.
 *
 * Paths are relative to `extension/`.
 */

import { readFileSync, readdirSync } from "node:fs";
import path from "node:path";

const TEST_RE = /^smoke-tests\/test-[^/]+\.ts$/;
const READS_RE = /\b(?:readFileSync|readdirSync|readFile|Bun\.file)\s*\(/;
// A repository path segment anywhere in the file: a quoted literal, a segment
// inside a template (`${dir}/src/x.ts`), or a bare `"src"` argument to
// path.join. Matching only a leading quote missed the template and join forms,
// which is how a reader escapes the list. Over-matching costs one test per round;
// under-matching is a gate that never looked.
const REPO_PATH_RE =
  /(?:^|[\/"'`\s(,])(?:src|smoke-tests\/lib|\.pi|modules|manifests|agents-base|pi-prompts|skill|docs|bin|dist|\.github|\.devcontainer|agents\.json|package\.json|bunfig\.toml|tsconfig[\w.-]*\.json|release-please-config\.json|Dockerfile|\.gitignore|install\.sh|build\.sh|README\.md|AGENTS\.md|CONTRIBUTING\.md|CHANGELOG\.md)(?=[\/"'`\s),]|$)/m;

/** Smoke test files (top level, extension-relative) that read repository text. */
export function textReadingTests(extensionDir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(path.join(extensionDir, "smoke-tests"))) {
    if (!TEST_RE.test(`smoke-tests/${name}`)) continue;
    const text = readFileSync(path.join(extensionDir, "smoke-tests", name), "utf8");
    if (READS_RE.test(text) && REPO_PATH_RE.test(text)) out.push(`smoke-tests/${name}`);
  }
  return out.sort();
}

